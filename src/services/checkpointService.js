function campaignChangedAfter(guildId, timelineId, sinceSeq, db) {
  return hasMessagesAfter({
    guildId,
    timelineId,
    channelIds: config.campaignChannelIds,
    sinceSeq
  }, db);
}


/** Private channels joined with the registered player who owns each. */
function getPrivateScopes(players) {
  return config.privateChannels
    .map(({ channelId, ownerId }) => ({
      channelId,
      player: players.find(p => p.discord_user_id === ownerId)
    }))
    .filter(scope => scope.player);
}

export async function getActiveCheckpoint(guildId) {
  const state = await stateRepo.getState(guildId);
  if (!state || state.version === 0) return null;
  return { ...state, ...toSnapshot(state) };
}

export async function getPendingDraft(guildId) {
  const draft = await checkpointRepo.getDraft(guildId);
  return draft ? { ...draft, ...toSnapshot(draft) } : null;
}

export function listCheckpointVersions(guildId) {
  return checkpointRepo.listVersions(guildId, CHECKPOINT_VERSIONS_LIST_LIMIT);
}

/**
 * Summarizes every campaign channel since the last boundary into a new
 * draft snapshot. Each audience is generated by a separate model call that
 * only receives what that audience may know (docs/DECISIONS.md, D-001):
 *
 *   shared     <- main channel + previous shared checkpoint
 *   character  <- main channel + own private channel + own previous knowledge
 *   dm_notes   <- everything
 *
 * The draft is discarded if the campaign moves on during generation.
 */
export async function createCheckpointDraft({ guildId, authorId }) {
  const state = await stateRepo.getState(guildId);
  const previous = toSnapshot(state);
  const isFirstVersion = state.version === 0;

  // High-water mark first: the draft covers (state.boundary_seq, boundarySeq].
  const [boundarySeq, boundaryAt] = await Promise.all([
    getHighWaterSeq(guildId),
    getDatabaseTime()
  ]);

  const historyOf = channelId => getHistory({
    guildId,
    channelId,
    timelineId: state.timeline_id,
    afterSeq: state.boundary_seq,
    untilSeq: boundarySeq
  });

  const [players, legacy, mainHistory, boundaryMessageId] =
    await Promise.all([
      getPlayers(guildId),
      getCampaignLegacyCheckpoint(guildId),
      historyOf(config.channels.main),
      getLatestMessageId({
        guildId,
        channelId: config.channels.main,
        timelineId: state.timeline_id,
        untilSeq: boundarySeq
      })
    ]);

  const privateScopes = await Promise.all(
    getPrivateScopes(players).map(async scope => {
      const name = scope.player.character_name;
      const previousKnowledge = previous.character_knowledge[name] || null;
      const legacySeed =
        !previousKnowledge && name === LEGACY_CHECKPOINT_CHARACTER
          ? legacy
          : null;

      return {
        ...scope,
        name,
        previousKnowledge,
        legacySeed,
        history: await historyOf(scope.channelId)
      };
    })
  );

  // A character gets a knowledge record once there is something to record
  // (D-003). Others keep whatever they had (possibly nothing).
  const activeScopes = privateScopes.filter(scope =>
    scope.history.length || scope.previousKnowledge || scope.legacySeed
  );

  const playerSummaries = players.map(toCharacterSummary);
  const characterNames = players.map(p => p.character_name);

  // NPC views for summarization inputs never include author_notes (D-007).
  const npcsKnownTo = readers => npcsFor(previous.npcs, readers, characterNames);

  const sharedTask = generateSharedCheckpoint({
    current_version: state.version,
    active_checkpoint: isFirstVersion ? null : previous.checkpoint,
    legacy_kraavok: isFirstVersion ? legacy : null,
    active_main_history: mainHistory,
    players: playerSummaries,
    npcs_known_to_everyone: npcsKnownTo(characterNames)
  });

  const characterTasks = activeScopes.map(async scope => [
    scope.name,
    await generateCharacterKnowledge({
      character: toCharacterSummary(scope.player),
      previous_knowledge: scope.previousKnowledge,
      legacy_personal_history: scope.legacySeed,
      shared_checkpoint: isFirstVersion ? null : previous.checkpoint,
      main_adventure_history: mainHistory,
      own_private_history: scope.history,
      npcs_known_to_character: npcsKnownTo([scope.name])
    })
  ]);

  const dmTask = generateDmNotes({
    previous_dm_notes: previous.dm_notes,
    shared_checkpoint: isFirstVersion ? null : previous.checkpoint,
    character_knowledge: previous.character_knowledge,
    legacy_kraavok: legacy,
    main_adventure_history: mainHistory,
    private_histories: Object.fromEntries(
      privateScopes.map(scope => [scope.name, scope.history])
    ),
    players: playerSummaries,
    npc_registry: previous.npcs
  });

  const npcTask = generateNpcUpdate({
    previous_npcs: previous.npcs,
    previous_dm_notes: previous.dm_notes,
    main_adventure_history: mainHistory,
    private_histories: Object.fromEntries(
      privateScopes.map(scope => [scope.name, scope.history])
    ),
    players: playerSummaries
  });

  const [checkpoint, characterEntries, dmNotes, npcList] = await Promise.all([
    sharedTask,
    Promise.all(characterTasks),
    dmTask,
    npcTask
  ]);

  const snapshot = {
    checkpoint,
    character_knowledge: {
      ...previous.character_knowledge,
      ...Object.fromEntries(characterEntries)
    },
    dm_notes: dmNotes,
    npcs: mergeUpdate(previous.npcs, npcList)
  };

  const latestState = await stateRepo.getState(guildId);

  if (
    latestState.version !== state.version ||
    latestState.timeline_id !== state.timeline_id
  ) {
    throw new UserFacingError('Campaign changed during draft generation. Retry.');
  }

  if (await campaignChangedAfter(guildId, state.timeline_id, boundarySeq)) {
    throw new UserFacingError(
      'New campaign messages arrived during draft generation. Retry.'
    );
  }

  await checkpointRepo.upsertDraft({
    guildId,
    snapshot,
    basedOnVersion: state.version,
    createdBy: authorId,
    timelineId: state.timeline_id,
    boundaryMessageId,
    boundaryAt,
    boundarySeq
  });

  return {
    ...snapshot,
    basedOnVersion: state.version,
    updatedCharacters: characterEntries.map(([name]) => name)
  };
}

/** Promotes the guild's draft to the active snapshot. Returns the new version. */
export function confirmCheckpointDraft({ guildId, userId }) {
  return withGuildTransaction(guildId, async db => {
    const draft = await checkpointRepo.getDraftForUpdate(db, guildId);

    if (!draft) {
      throw new UserFacingError('No checkpoint draft exists.');
    }

    if (draft.created_by !== userId) {
      throw new UserFacingError('Only the draft creator can confirm it.');
    }

    const state = await stateRepo.getStateForUpdate(db, guildId);

    if (
      !state ||
      state.version !== draft.based_on_version ||
      state.timeline_id !== draft.timeline_id
    ) {
      throw new UserFacingError(
        'Campaign checkpoint or timeline changed. Create a new draft.'
      );
    }

    if (await campaignChangedAfter(guildId, state.timeline_id, draft.boundary_seq, db)) {
      throw new UserFacingError(
        'New campaign messages arrived after the draft. ' +
        'Use /checkpoint save again.'
      );
    }

    const version = state.version + 1;
    const snapshot = toSnapshot(draft);

    await stateRepo.advanceCheckpoint(db, {
      guildId,
      snapshot,
      version,
      boundaryAt: draft.boundary_at,
      boundarySeq: draft.boundary_seq
    });

    await checkpointRepo.insertVersion(db, {
      guildId,
      version,
      snapshot,
      createdBy: userId,
      reason: 'save',
      timelineId: state.timeline_id,
      boundaryMessageId: draft.boundary_message_id,
      boundaryAt: draft.boundary_at,
      boundarySeq: draft.boundary_seq
    });

    await checkpointRepo.deleteDraft(guildId, db);

    return { version };
  });
}

/**
 * Restores an earlier snapshot (all partitions) as a new version on a fresh
 * timeline. Messages from the abandoned timeline stay stored but unused.
 */
export function rollbackCheckpoint({ guildId, userId, targetVersion }) {
  return withGuildTransaction(guildId, async db => {
    const state = await stateRepo.getStateForUpdate(db, guildId);

    if (!state || state.version === 0) {
      throw new UserFacingError('No saved checkpoint exists.');
    }

    if (
      !Number.isSafeInteger(targetVersion) ||
      targetVersion < 1 ||
      targetVersion > state.version
    ) {
      throw new UserFacingError('Invalid checkpoint version.');
    }

    const target = await checkpointRepo.getVersion(guildId, targetVersion, db);

    if (!target) {
      throw new UserFacingError(`Checkpoint v${targetVersion} not found.`);
    }

    const version = state.version + 1;
    const timelineId = randomUUID();
    const snapshot = toSnapshot(target);

    await stateRepo.resetToTimeline(db, {
      guildId,
      snapshot,
      version,
      timelineId
    });

    await checkpointRepo.insertVersion(db, {
      guildId,
      version,
      snapshot,
      createdBy: userId,
      reason: `rollback to v${targetVersion}`,
      timelineId
    });

    await checkpointRepo.deleteDraft(guildId, db);

    return { restoredVersion: targetVersion, version, timelineId };
  });
}

/**
 * Applies a DM-authored change to the active snapshot as a new version on
 * the same timeline, keeping the history boundary (e.g. an NPC note).
 * `mutate(snapshot)` receives a deep copy and returns the new snapshot.
 */
export function amendActiveSnapshot({ guildId, userId, reason, mutate }) {
  return withGuildTransaction(guildId, async db => {
    const state = await stateRepo.getStateForUpdate(db, guildId);

    if (!state || state.version === 0) {
      throw new UserFacingError('Save a first checkpoint before editing campaign data.');
    }

    const snapshot = mutate(structuredClone(toSnapshot(state)));
    const version = state.version + 1;

    await stateRepo.replaceSnapshot(db, { guildId, snapshot, version });

    await checkpointRepo.insertVersion(db, {
      guildId,
      version,
      snapshot,
      createdBy: userId,
      reason,
      timelineId: state.timeline_id,
      boundaryAt: state.boundary_at,
      boundarySeq: state.boundary_seq
    });

    return { version };
  });
}

/** Returns true if the user's draft was removed. */
export function cancelCheckpointDraft({ guildId, userId }) {
  return checkpointRepo.deleteDraftOwnedBy(guildId, userId);
}
